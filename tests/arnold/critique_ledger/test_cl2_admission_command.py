class TestU1AcceptedBundle:
    def _u1_dir(self):
        val = os.environ.get(U1_DIR_ENV)
        if not val:
            return None
        p = Path(val)
        return p if p.is_dir() else None

    def test_real_u1_bundle_accepted(self, tmp_path):
        u1 = self._u1_dir()
        if u1 is None:
            pytest.skip(f"U1 accepted bundle not supplied (set ${U1_DIR_ENV})")
        meta_path = u1 / "bundle_meta.json"
        if not meta_path.is_file():
            pytest.skip("U1 bundle_meta.json not found")
        meta = _load_json(meta_path)
        manifest = {
            "amended_handoff": {
                "path": str(u1 / "amended_handoff.json"),
                "sha256": meta["amended_handoff_sha256"],
            },
            "policy_bundle": {
                "path": str(u1 / "policy_bundle.json"),
                "sha256": meta["policy_bundle_sha256"],
            },
            "review_receipt": {
                "path": str(u1 / "review_receipt.json"),
                "sha256": meta["review_receipt_sha256"],
            },
            "reviewer_trust": {
                "path": str(u1 / "reviewer_trust.json"),
                "sha256": meta["reviewer_trust_sha256"],
            },
            "reviewer_fingerprint": meta["reviewer_fingerprint"],
            "target_schema": meta["target_schema"],
            "amendment_checksum": meta["amendment_checksum"],
            "policy_revisions": meta["policy_revisions"],
        }
        manifest_path = tmp_path / "manifest.json"
        _write_json(manifest_path, manifest)
        result = _run(manifest_path)
        assert result.returncode == EXIT_OK
        stdout = result.stdout.rstrip("\n")
        assert len(stdout) == 64
