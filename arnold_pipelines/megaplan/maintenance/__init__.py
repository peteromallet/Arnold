def __getattr__(name: str) -> Any:
    """Resolve an M3/M4 API name from its source module (PEP 562, lazy).

    Every name in :data:`M4_API` (and the wider package ``__all__``) is
    resolved on first access from its canonical source submodule, then cached
    on the package so repeated access is cheap and object identity is stable.
    Unknown names raise ``AttributeError`` exactly like a normal module.
    """
    entry = _M4_LAZY_IMPORTS.get(name)
    if entry is None:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    module_name, attr = entry
    module = importlib.import_module(f"{__name__}.{module_name}")
    value = getattr(module, attr)
    globals()[name] = value
    return value


