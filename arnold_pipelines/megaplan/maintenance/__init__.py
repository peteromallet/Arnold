"""Maintenance observations and authority joins (M2 bridge, M3 freeze).

The Maintenance package is the M2 substrate for coherent maintenance
observations over the accepted Run Authority, WBC, Custody, M11 conformance,
and Native Parity sources.  It ships in shadow/report mode only: enforcement,
autonomy, repair policy, daily baselines, and lifecycle mutation stay disabled.

This package exposes the strict foundation (one canonical serializer / strict
decoder, typed nullable identities, locator-only immutable owner references,
and validated UTC event times, half-open windows, watermarks, lateness, and
correction links) from :mod:`identity`.  The M3 freeze (Plan Step 15) adds the
stable M4-facing API surface on top — the owner-source join
(:class:`~arnold_pipelines.megaplan.maintenance.contracts.ObservationEnvelope`
and :func:`~arnold_pipelines.megaplan.maintenance.observation.capture_observation`),
the occurrence-bound request reference contracts
(:mod:`~arnold_pipelines.megaplan.maintenance.operations` and
:mod:`~arnold_pipelines.megaplan.maintenance.events`), the replayable
checkpoint scheduler (:mod:`~arnold_pipelines.megaplan.maintenance.checkpoints`),
recurrence/escalation links, the independent verification surface
(:mod:`~arnold_pipelines.megaplan.maintenance.verification`), and the frozen
M3 handoff view (:mod:`~arnold_pipelines.megaplan.maintenance.handoffs`) —
resolved lazily through :func:`__getattr__` so importing the package never
pulls the heavier modules and never creates an import cycle with the incident
schema (which itself imports the identity foundation).

The package remains reference-only (SD1): it never constructs an owner
authority record and never calls a canonical owner seam; only the cloud
adapters (``arnold_pipelines.megaplan.cloud.maintenance_recovery`` /
``maintenance_canary``) may call those seams.
"""

